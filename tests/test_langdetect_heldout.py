"""Regression guard: the language check on 80 real, hand-reviewed LLM responses.

The corpus (``fixtures/langdetect_heldout.jsonl``) was generated by
``scripts/build_lang_corpus.py`` from qwen2.5:7b and llama3.1:8b, then read in
full to set each row's true language. It was scored once before any tuning:
72/78 decided, 72/72 correct, 0 false "mixed" flags. If a change to the
detector or its word lists moves these numbers, this test says so.
"""

import json
from pathlib import Path

import pytest

from evalkit.checks import LanguageCheck, Status

CORPUS = Path(__file__).parent / "fixtures" / "langdetect_heldout.jsonl"


@pytest.fixture(scope="module")
def rows() -> list[dict]:
    return [json.loads(line) for line in CORPUS.read_text(encoding="utf-8").splitlines()]


def test_corpus_shape(rows: list[dict]) -> None:
    assert len(rows) == 80
    labels = [r["label"] for r in rows]
    assert labels.count("en") == 39
    assert labels.count("id") == 39
    assert labels.count(None) == 2


def test_no_false_alarms_and_high_coverage(rows: list[dict]) -> None:
    outcomes = [
        LanguageCheck(expected=r["label"]).check(r["text"]).status
        for r in rows
        if r["label"] is not None
    ]
    # Every response really is in the expected language, so any FAIL is a false alarm.
    assert outcomes.count(Status.FAIL) == 0
    decided = len(outcomes) - outcomes.count(Status.SKIP)
    assert decided / len(outcomes) >= 0.90


def test_wrong_expectation_is_caught(rows: list[dict]) -> None:
    # Flip the expected language: every decided row must now fail (no missed mismatches).
    flipped = {"en": "id", "id": "en"}
    outcomes = [
        LanguageCheck(expected=flipped[r["label"]]).check(r["text"]).status
        for r in rows
        if r["label"] is not None
    ]
    assert outcomes.count(Status.PASS) == 0
    assert outcomes.count(Status.FAIL) >= 70
